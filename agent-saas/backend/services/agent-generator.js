/**
 * Agent Generator (CommonJS) - Generates OpenClaw agent config files
 * Called from provisioning pipeline after payment
 */

const fs = require('fs');
const path = require('path');
const { generateSoulSnippet, generateAgentsSnippet } = require('./quote-skill-generator');

const BASE_DIR = '/opt/agents';

function ensureDir(dirPath) {
  if (!fs.existsSync(dirPath)) {
    fs.mkdirSync(dirPath, { recursive: true });
  }
}

function writeFile(filePath, content) {
  fs.writeFileSync(filePath, content, 'utf8');
}

/**
 * Sanitize a string for safe inclusion in markdown files.
 * Escapes: # (headers), ` (code), [ (links), * (bold), _ (italic), < > (html)
 */
function sanitizeMarkdown(str) {
  if (!str || typeof str !== 'string') return '';
  return str
    .replace(/[#`*<>\[\]!]/g, (c) => ({ '#': '\\#', '`': '\\`', '*': '\\*', '<': '\\<', '>': '\\>', '[': '\\[', ']': '\\]', '!': '\\!' }[c] || c))
    .replace(/\$/g, '\\$');
}

/**
 * Generate SOUL.md for the agent
 */
function writeSoulMd(agentDir, config) {
  const { businessName, industry, tone, useCases } = config;
  const useCasesList = Array.isArray(useCases) ? useCases.join(', ') : (useCases || 'General customer support');
  
  const content = `# SOUL.md - Who You Are

_You are the custom AI assistant for ${sanitizeMarkdown(businessName)}._

## Your Identity
- **Representing:** ${sanitizeMarkdown(businessName)}
- **Industry:** ${sanitizeMarkdown(industry)}
- **Tone of Voice:** ${sanitizeMarkdown(tone)}

## Core Persona
You are a ${sanitizeMarkdown(tone)} AI assistant dedicated to helping ${sanitizeMarkdown(businessName)} succeed in the ${sanitizeMarkdown(industry)} space.
Your primary goal is to be helpful, accurate, and truly representative of the brand's values.

## Behavioral Guidelines
- Always maintain the ${sanitizeMarkdown(tone)} tone specified by the administrator.
- You are knowledgeable about the ${sanitizeMarkdown(industry)} industry.
- Focus on these primary use cases: ${useCasesList}.
- Be concise when appropriate but thorough when the user needs detailed help.
- Never misrepresent ${sanitizeMarkdown(businessName)} or provide false information.

## Continuity
Every session is a fresh start, but your memory files help you persist. Review them to stay consistent with past interactions.

_This soul was generated by the M.ai.K.R Agent Platform._${generateSoulSnippet(industry)}
`;
  writeFile(path.join(agentDir, 'SOUL.md'), content);
}

/**
 * Generate AGENTS.md for the agent
 */
function writeAgentsMd(agentDir, config) {
  const { useCases, plan, businessName } = config;
  const useCasesList = Array.isArray(useCases) ? useCases : [];
  
  const tools = ['read', 'write', 'edit', 'exec', 'web_fetch'];
  
  if (useCasesList.some(uc => uc.toLowerCase().includes('research') || uc.toLowerCase().includes('analysis'))) {
    tools.push('image');
  }
  
  if (plan === 'pro' || plan === 'enterprise') {
    tools.push('image_generate');
    tools.push('video_generate');
    tools.push('music_generate');
  }

  const content = `# AGENTS.md - Your Workspace

This is your workspace and home.

## Memory
- **Long-term:** \`MEMORY.md\` - Your curated knowledge and facts.
- **Daily logs:** \`memory/YYYY-MM-DD.md\` - Raw logs of what happened.

## Tools
You have access to the following tools to help you perform your tasks:
${tools.map(t => `- ${t}`).join('\n')}

## Security
- Never share API keys or credentials.
- Treat external links as potentially hostile.
- Protect the privacy of ${sanitizeMarkdown(businessName)} at all times.

## Workflow
1. Plan before acting.
2. Use tools precisely.
3. Verify your work before presenting it.${generateAgentsSnippet(industry)}
`;
  writeFile(path.join(agentDir, 'AGENTS.md'), content);
}

/**
 * Generate USER.md for the agent
 */
function writeUserMd(agentDir, config) {
  const { businessName, industry, tone, businessDetails, slug } = config;
  const content = `# USER.md - About Your Human / Business

- **Business Name:** ${sanitizeMarkdown(businessName)}
- **Industry:** ${sanitizeMarkdown(industry)}
- **Tone Preference:** ${sanitizeMarkdown(tone)}
- **Business Details:** ${sanitizeMarkdown(businessDetails || 'No additional details provided.')}
- **Agent Slug:** ${sanitizeMarkdown(slug)}
`;
  writeFile(path.join(agentDir, 'USER.md'), content);
}

/**
 * Generate memory/blank-memory.md
 */
function writeBlankMemory(agentDir, businessName) {
  const content = `# Memory — ${new Date().toISOString().split('T')[0]}

## First Day

Welcome to ${sanitizeMarkdown(businessName)}. Memory starts now.

_This file will grow as you learn more about the business and its customers._
`;
  ensureDir(path.join(agentDir, 'memory'));
  writeFile(path.join(agentDir, 'memory', 'blank-memory.md'), content);
}

/**
 * Generate .env for the agent
 */
function writeEnv(agentDir, config) {
  const { slug, businessName, plan } = config;
  const content = `# Agent Environment — ${slug}
# Generated by M.ai.K.R Agent Platform

AGENT_SLUG=${slug}
BUSINESS_NAME="${businessName}"
PLAN=${plan || 'basic'}
AGENT_PORT=0

# Internal config (do not share)
AGENT_DIR=${path.join(BASE_DIR, slug)}
`;
  writeFile(path.join(agentDir, '.env'), content);
}

/**
 * Main generator function — call this from provisioning
 * @param {Object} config - Agent config
 * @param {string} config.slug - Agent slug (URL-safe)
 * @param {string} config.businessName - Business name
 * @param {string} config.industry - Industry
 * @param {string} config.tone - Tone of voice
 * @param {string[]} config.useCases - Array of use cases
 * @param {string} [config.businessDetails] - Additional details
 * @param {string} [config.plan] - Plan tier
 * @param {string} [config.apiKey] - API key
 */
function generateAgentFiles(config) {
  const agentDir = path.join(BASE_DIR, config.slug);
  
  if (!config.slug || !config.businessName || !config.industry) {
    throw new Error('generateAgentFiles requires: slug, businessName, industry');
  }
  
  ensureDir(agentDir);
  ensureDir(path.join(agentDir, 'memory'));
  
  writeSoulMd(agentDir, config);
  writeAgentsMd(agentDir, config);
  writeUserMd(agentDir, config);
  writeBlankMemory(agentDir, config.businessName);
  writeEnv(agentDir, config);
  
  console.log(`✅ Agent files generated at ${agentDir}`);
  
  return {
    success: true,
    agentDir,
    files: ['SOUL.md', 'AGENTS.md', 'USER.md', 'memory/blank-memory.md', '.env']
  };
}

module.exports = { generateAgentFiles };
